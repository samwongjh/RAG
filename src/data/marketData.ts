// Deterministic candle generator to produce realistic multi-timeframe charts
function generateCandles(basePrice: number, count: number, volatility: number, trend: number): Candle[] {
  const candles: Candle[] = [];
  let currentClose = basePrice * (1 - (trend * count * 0.002));
  const now = Date.now();
  const stepMs = 86400000; // 1 day

  for (let i = count - 1; i >= 0; i--) {
    const timestamp = now - i * stepMs;
    const dateObj = new Date(timestamp);
    const time = `${dateObj.getMonth() + 1}/${dateObj.getDate()}`;
    
    // Random walk with trend
    const changePercent = (Math.sin(i * 0.4) * 0.5 + (Math.random() - 0.48)) * volatility + (trend * 0.002);
    const open = currentClose;
    const close = Math.max(open * (1 + changePercent), 0.01);
    const high = Math.max(open, close) * (1 + Math.random() * (volatility * 0.8));
    const low = Math.min(open, close) * (1 - Math.random() * (volatility * 0.8));
    const volume = Math.round((Math.random() * 0.8 + 0.6) * 15000000);

    candles.push({
      time,
      timestamp,
      open: Number(open.toFixed(open > 100 ? 2 : 4)),
      high: Number(high.toFixed(high > 100 ? 2 : 4)),
      low: Number(low.toFixed(low > 100 ? 2 : 4)),
      close: Number(close.toFixed(close > 100 ? 2 : 4)),
      volume,
    });

    currentClose = close;
  }

  // Ensure last candle matches basePrice roughly
  if (candles.length > 0) {
    const last = candles[candles.length - 1];
    last.close = basePrice;
    last.high = Math.max(last.high, basePrice);
    last.low = Math.min(last.low, basePrice);
  }

  return candles;
}

function generateHistory(price: number, volatility: number, trend: number) {
  return {
    '1D': generateCandles(price, 24, volatility * 0.5, trend),
    '5D': generateCandles(price, 30, volatility * 0.7, trend),
    '1M': generateCandles(price, 30, volatility, trend),
    '6M': generateCandles(price, 60, volatility * 1.2, trend),
    '1Y': generateCandles(price, 100, volatility * 1.5, trend),
    'ALL': generateCandles(price, 120, volatility * 2.0, trend),
  };
}

function extractSparkline(candles: Candle[]): number[] {
  return candles.slice(-15).map(c => c.close);
}

